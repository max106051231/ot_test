print("問題：", item["question"])
print("\n模型寫的 SQL：\n", pred_sql)
print("\n標準答案 SQL：\n", item["SQL"])
ok, err = is_correct(item["db_id"], pred_sql, item["SQL"])
print("\n結果：", "✅ 答對" if ok else f"❌ 答錯 {err}")

"""## 步驟 6：正式跑分（主實驗：有 evidence）

逐題請模型作答並判斷對錯，最後算出 EX。結果會存成 `results_with_evidence.csv`，可以下載回來用 Excel 打開。
"""

import pandas as pd

def evaluate(items, use_evidence=True, label=""):
    records = []
    for i, item in enumerate(items, 1):
        try:
            pred_sql = generate_pred_sql(item, use_evidence)
            ok, err = is_correct(item["db_id"], pred_sql, item["SQL"])
        except RuntimeError as e:          # API 本身出錯（不是模型答錯）
            pred_sql, ok, err = "", False, str(e)
        records.append({
            "編號": i,
            "資料庫": item["db_id"],
            "難度": item.get("difficulty", ""),
            "問題": item["question"],
            "evidence": item.get("evidence", ""),
            "模型SQL": pred_sql,
            "標準SQL": item["SQL"],
            "答對": ok,
            "錯誤訊息": err,
        })
        done = sum(r["答對"] for r in records)
        print(f"\r{label} 進度 {i}/{len(items)}，目前答對 {done} 題", end="")
    print()
    return pd.DataFrame(records)

subset = questions[:N_QUESTIONS]
df_with = evaluate(subset, use_evidence=True, label="[有 evidence]")
df_with.to_csv("results_with_evidence.csv", index=False, encoding="utf-8-sig")
ex_with = df_with["答對"].mean() * 100
print(f"\n🎯 你的 EX（有 evidence，{len(subset)} 題）：{ex_with:.1f}%")

"""## 步驟 7：小實驗——拿掉 evidence 會怎樣？

同樣的題目，這次**不給**提示。兩個分數的差距，就是「外部知識」對模型的幫助有多大。
"""

df_without = evaluate(subset, use_evidence=False, label="[無 evidence]")
df_without.to_csv("results_without_evidence.csv", index=False, encoding="utf-8-sig")
ex_without = df_without["答對"].mean() * 100

summary = pd.DataFrame({
    "設定": ["有 evidence", "無 evidence"],
    "EX (%)": [round(ex_with, 1), round(ex_without, 1)],
})
print(summary.to_string(index=False))
print(f"\n差距：{ex_with - ex_without:+.1f} 個百分點")

"""## 步驟 8：看看依難度分的成績，以及答錯的題目

只看總分學不到東西，**看答錯的題目**才是今天最有價值的部分。
"""

if df_with["難度"].astype(bool).any():
    print("依難度分的 EX（有 evidence）：")
    print((df_with.groupby("難度")["答對"].mean() * 100).round(1).to_string())

wrong = df_with[~df_with["答對"]]
print(f"\n答錯 {len(wrong)} 題，以下列出前 3 題：")
for _, r in wrong.head(3).iterrows():
    print("─" * 60)
    print("問題　　：", r["問題"])
    print("evidence：", r["evidence"])
    print("模型 SQL：", r["模型SQL"])
    print("標準 SQL：", r["標準SQL"])
    if r["錯誤訊息"]:
        print("錯誤　　：", r["錯誤訊息"])

